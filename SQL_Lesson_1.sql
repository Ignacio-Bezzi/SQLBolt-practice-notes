   TOPIC: SELECT
============================================
NOTES:
   - Query: A statement that declares what data we want and where to find it.
   - Core Concepts: 
     > Table = Entity (e.g., Dogs)
     > Row = Specific instance (e.g., A pug)
     > Column = Shared property (e.g., Fur color)
     
   SYNTAX:
   - SELECT col1, col2 FROM table; -> Retrieves specific columns.
   - SELECT * FROM table; -> Retrieves ALL columns (useful for a quick inspection).
========================================= */


NOTES:
   - The WHERE clause filters specific rows to make results manageable and queries faster.
   - Multiple conditions can be combined using AND / OR logical keywords.
   - Convention: Always capitalize SQL keywords (SELECT, WHERE, etc.) to easily distinguish them from column or table names.
   
   SYNTAX & NUMERICAL OPERATORS:
   - SELECT columns FROM table WHERE condition;
   - =, !=, <, <=, >, >= : Standard numerical operators.
   - BETWEEN ... AND ... : Number is within a range (inclusive).
   - IN (...) : Number exists in a specific list (e.g., IN (2, 4, 6)).
   - PRO TIP: You can add NOT before BETWEEN or IN to get the exact opposite.
